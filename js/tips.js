// 获取今日Tips（根据纪念日判断是异地还是见面）
// 基于日期确定性选择，同一天始终返回同一条
function getTodayTip(anniversaries) {
  const today = new Date();
  const todayStr = today.toISOString().slice(0, 10);

  // 用日期生成确定性索引
  const dateHash = _hashStr(todayStr);

  // 检查今天是不是见面日
  if (anniversaries && anniversaries.length > 0) {
    const isMeetup = anniversaries.some(a => {
      if (!a.date) return false;
      const isMeetup = (a.title || a.label || '').includes('见面') ||
                       (a.type || '').includes('见面') ||
                       (a.tags && a.tags.some(t => t.includes('见面')));
      return isMeetup && a.date === todayStr;
    });
    if (isMeetup) {
      return TIPS_TOGETHER[dateHash % TIPS_TOGETHER.length];
    }
  }

  // 异地模式：从异地 + 通用中确定性选择
  const pool = [...TIPS_LDR, ...TIPS_COMMON];
  return pool[dateHash % pool.length];
}

function _hashStr(str) {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = ((hash << 5) - hash) + str.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}
